$('#captureSelfieBtn')?.addEventListener('click', async()=>{
  const video=$('#cameraVideo'); const canvas=$('#selfieCanvas');
  if(!video.videoWidth) return;
  canvas.width=video.videoWidth; canvas.height=video.videoHeight;
  const ctx=canvas.getContext('2d');
  ctx.translate(canvas.width,0); ctx.scale(-1,1); ctx.drawImage(video,0,0,canvas.width,canvas.height);
  const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/jpeg',0.92));
  if(!blob) return;
  const file=new File([blob],`selfie-${Date.now()}.jpg`,{type:'image/jpeg'});
  const url=URL.createObjectURL(blob);
  await stopCamera(); updateSelfieReady(file,url);
});

